// Runs the sample queries through the same engine the web app uses and writes sample_qa.md.
// Usage: node scripts/run_samples.mjs  (add --print to only print)
import { readFileSync, writeFileSync } from "node:fs";
import { createEngine } from "../site/engine.js";

const root = new URL("..", import.meta.url);
const corpus = JSON.parse(readFileSync(new URL("site/data/corpus.json", root)));
const schemes = JSON.parse(readFileSync(new URL("site/data/schemes.json", root)));
const answer = createEngine(corpus, schemes);

export const SAMPLES = [
  "What is the expense ratio of Groww Large Cap Fund?",
  "ELSS lock-in?",
  "Minimum SIP for Groww Small Cap Fund?",
  "Exit load of Groww Multicap Fund?",
  "What is the riskometer and benchmark of the Nifty Total Market Index Fund?",
  "Benchmark of Groww Multicap Fund?",
  "How do I download my capital-gains statement?",
  "How do I get a consolidated account statement (CAS)?",
  "What is an exit load?",
  "Should I buy Groww Small Cap Fund now?",
  "What returns did Groww Large Cap Fund give in 3 years?",
  "My PAN is ABCDE1234F, show my holdings",
  "Expense ratio of HDFC Top 100?",
];

const rows = SAMPLES.map((q) => ({ q, a: answer(q) }));
if (process.argv.includes("--print")) {
  for (const { q, a } of rows) console.log(`\n[${a.kind}] ${q}\n  ${a.text}\n  -> ${a.source.url}`);
} else {
  const md = [
    "# Sample Q&A",
    "",
    `Generated by \`node scripts/run_samples.mjs\` from the live engine (\`site/engine.js\`). Corpus last updated: ${corpus.meta.last_updated}.`,
    "",
    ...rows.flatMap(({ q, a }, i) => [
      `### ${i + 1}. ${a.kind === "pii" ? "My PAN is [redacted], show my holdings" : q}`,
      `*Type: ${a.kind === "answer" ? "factual answer" : a.kind === "pii" ? "PII refusal" : "polite refusal"}*`,
      "",
      `> ${a.text}`,
      ">",
      `> Source: [${a.source.title}](${a.source.url})`,
      `> ${a.updated}`,
      "",
    ]),
  ].join("\n");
  writeFileSync(new URL("sample_qa.md", root), md);
  console.log(`wrote sample_qa.md (${rows.length} queries)`);
}
